function updatePortfolio() {
  const inputs = document.querySelectorAll("#allocationList input");
  let total = 0;
  let preview = [];

  inputs.forEach(input => {
    const value = Number(input.value) || 0;
    total += value;
    if (value > 0) preview.push({ brand: input.dataset.brand, value });
  });

  const totalElement = document.getElementById("totalAllocated");
  totalElement.textContent = `${total} / 100`;
  totalElement.style.color = total === 100 ? "#81ffb0" : total > 100 ? "#ff7272" : "#f4f7fb";

  const previewBox = document.getElementById("portfolioPreview");
  if (preview.length === 0) {
    previewBox.innerHTML = `<p>${t("no_allocation_text")}</p>`;
  } else {
    previewBox.innerHTML = preview.map(item => `
      <div class="preview-row">
        <span>${item.brand}</span>
        <strong>${item.value} pts</strong>
      </div>
    `).join("");
  }

  const footer = document.querySelector(".card-footer");
  footer.classList.remove("published");
  footer.querySelector("strong").textContent = "NOT YET";

  const profileList = document.getElementById("profilePortfolioPreview");
  if (profileList) {
    if (preview.length === 0) {
      profileList.innerHTML = `<p>${t("no_profile_portfolio")}</p>`;
    } else {
      profileList.innerHTML = preview.map(item => `
        <div class="profile-portfolio-row">
          <span>${item.brand}</span>
          <strong>${item.value} pts</strong>
        </div>
      `).join("");
    }
  }
}

