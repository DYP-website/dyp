function renderChart() {
  const svg = document.getElementById("scoreChart");
  const legend = document.getElementById("chartLegend");
  const labels = ranges[selectedRange];
  const width = 900;
  const height = 420;
  const pad = { left: 52, right: 28, top: 24, bottom: 46 };
  const chartW = width - pad.left - pad.right;
  const chartH = height - pad.top - pad.bottom;

  const allValues = selectedBrands.flatMap(name => scoreSeries[selectedRange][name] || []);
  const min = Math.max(0, Math.min(...allValues, 50) - 5);
  const max = Math.min(100, Math.max(...allValues, 95) + 5);

  function x(i) {
    return pad.left + (labels.length === 1 ? chartW / 2 : (i / (labels.length - 1)) * chartW);
  }

  function y(value) {
    return pad.top + ((max - value) / (max - min)) * chartH;
  }

  let html = "";

  for (let g = 0; g <= 4; g++) {
    const value = min + ((max - min) / 4) * g;
    const yy = y(value);
    html += `<line class="grid-line" x1="${pad.left}" y1="${yy}" x2="${width - pad.right}" y2="${yy}"></line>`;
    html += `<text class="axis-label" x="8" y="${yy + 4}">${Math.round(value)}</text>`;
  }

  html += `<line class="axis-line" x1="${pad.left}" y1="${height - pad.bottom}" x2="${width - pad.right}" y2="${height - pad.bottom}"></line>`;
  html += `<line class="axis-line" x1="${pad.left}" y1="${pad.top}" x2="${pad.left}" y2="${height - pad.bottom}"></line>`;

  labels.forEach((label, i) => {
    html += `<text class="axis-label" x="${x(i)}" y="${height - 16}" text-anchor="middle">${label}</text>`;
  });

  selectedBrands.forEach(name => {
    const brand = brands.find(b => b.name === name);
    const values = scoreSeries[selectedRange][name];
    if (!values) return;

    const points = values.map((v, i) => `${x(i)},${y(v)}`).join(" ");
    html += `<polyline class="line-path" points="${points}" stroke="${brand.color}"></polyline>`;

    values.forEach((v, i) => {
      html += `<circle class="dot" cx="${x(i)}" cy="${y(v)}" r="5" fill="${brand.color}"></circle>`;
    });
  });

  svg.innerHTML = html;

  legend.innerHTML = selectedBrands.length
    ? selectedBrands.map(name => {
      const brand = brands.find(b => b.name === name);
      return `<div class="legend-item"><span class="legend-dot" style="background:${brand.color}"></span>${name}</div>`;
    }).join("")
    : `<div class="legend-item">Seleziona almeno un brand</div>`;

  updateInsight();
}

function updateInsight() {
  const insight = document.getElementById("analyticsInsight");
  if (!selectedBrands.length) {
    insight.textContent = "Seleziona almeno un brand per generare un insight.";
    return;
  }

  const deltas = selectedBrands.map(name => {
    const values = scoreSeries[selectedRange][name];
    return { name, delta: values[values.length - 1] - values[0] };
  }).sort((a, b) => b.delta - a.delta);

  const best = deltas[0];
  insight.textContent = `${best.name} mostra il momentum più forte nell’intervallo ${selectedRange}: ${best.delta >= 0 ? "+" : ""}${best.delta} punti DYP.`;
}

